/**
 * Writes supabase/seed.sql from the Northwind Labs demo dataset.
 * Run with `pnpm db:seed:generate`, then `pnpm db:reset` to load it.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { northwind } from "../src/server/demo/northwind";

type Row = Record<string, unknown>;

/** Columns stored as text[] (everything else that's an array is jsonb). */
const TEXT_ARRAY_COLUMNS = new Set(["targets"]);

function literal(column: string, value: unknown): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") return String(value);
  if (Array.isArray(value) && TEXT_ARRAY_COLUMNS.has(column)) {
    return `array[${value.map((v) => quote(String(v))).join(", ")}]::text[]`;
  }
  if (typeof value === "object") return `${quote(JSON.stringify(value))}::jsonb`;
  return quote(String(value));
}

function quote(s: string): string {
  return `'${s.replaceAll("'", "''")}'`;
}

function insert(table: string, rows: Row[], omit: string[] = []): string {
  if (rows.length === 0) return "";
  const columns = Object.keys(rows[0]!).filter((c) => !omit.includes(c));
  const values = rows.map((r) => `  (${columns.map((c) => literal(c, r[c])).join(", ")})`);
  return `insert into ${table} (${columns.join(", ")}) values\n${values.join(",\n")};\n`;
}

const d = northwind;

const authUsers = d.users.map((u) => ({
  instance_id: "00000000-0000-0000-0000-000000000000",
  id: u.id,
  aud: "authenticated",
  role: "authenticated",
  email: u.email,
  encrypted_password: "",
  email_confirmed_at: u.created_at,
  raw_app_meta_data: { provider: "github", providers: ["github"] },
  raw_user_meta_data: { user_name: u.login, full_name: u.name },
  created_at: u.created_at,
  updated_at: u.created_at,
  confirmation_token: "",
  recovery_token: "",
  email_change_token_new: "",
  email_change: "",
}));

const sql = [
  "-- Northwind Labs demo data. GENERATED by apps/web/scripts/generate-seed.ts — do not edit by hand.",
  "-- Regenerate with `pnpm db:seed:generate`.",
  "",
  "-- Profiles are created from auth.users by the on_auth_user_created trigger.",
  insert("auth.users", authUsers),
  insert("public.workspaces", d.workspaces),
  insert("public.workspace_members", d.workspaceMembers),
  insert("public.invitations", d.invitations),
  insert("public.github_installations", d.githubInstallations),
  insert("public.repositories", d.repositories),
  "-- current_version_id is set after versions exist (circular reference).",
  insert("public.policies", d.policies, ["current_version_id"]),
  insert("public.policy_versions", d.policyVersions),
  ...d.policies.map(
    (p) =>
      `update public.policies set current_version_id = ${quote(p.current_version_id!)} where id = ${quote(p.id)};\n`,
  ),
  insert("public.policy_assignments", d.policyAssignments),
  insert("public.repo_exemptions", d.repoExemptions),
  insert("public.repo_file_states", d.repoFileStates),
  insert("public.rollouts", d.rollouts),
  insert("public.rollout_items", d.rolloutItems),
  insert("public.sync_pull_requests", d.syncPullRequests),
  insert("public.audit_events", d.auditEvents),
].join("\n");

const out = resolve(import.meta.dirname, "../../../supabase/seed.sql");
writeFileSync(out, sql);
console.log(`Wrote ${out}`);
